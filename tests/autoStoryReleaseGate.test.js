const assert = require('node:assert/strict');
const Gate = require('../electron/services/autoStoryReleaseGate');
const pass = { finalCheck: { verdict: 'PASS' }, needsUserReview: false };
const media = { width: 1080, height: 1920, duration: 78.4, hasAudio: true };
const cfg = { targetDurationMinSec: 65, targetDurationMaxSec: 90 };
assert.equal(Gate.assess({ audit: pass, media, bytes: 100000, file: 'final.mp4', config: cfg }).status, 'ready_to_publish');
assert.equal(Gate.assess({ audit: pass, media: { ...media, width: 1920, height: 1080 }, bytes: 100000, file: 'final.mp4', config: cfg }).status, 'needs_attention');
assert.equal(Gate.assess({ audit: pass, media, bytes: 100000, file: 'final.mp4', config: cfg, renderQa: { passed: false } }).status, 'needs_attention');
assert.equal(Gate.assess({ audit: { finalCheck: { verdict: 'FAIL' } }, media, bytes: 100000, file: 'final.mp4', config: cfg }).status, 'needs_attention');
assert.equal(Gate.assess({ audit: pass, media, bytes: 0, file: 'final.mp4', config: cfg }).status, 'needs_attention');
console.log('autoStoryReleaseGate tests passed');
